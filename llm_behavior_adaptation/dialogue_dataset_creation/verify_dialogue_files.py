#!/usr/bin/env python3
"""
Verify generated dialogue files for completeness and correctness.

This script verifies dialogue files generated by the dialogue generation pipeline
(langgraph_generation_controller.py) to ensure data quality and completeness.

Checks performed:
1. Total number of lines in each dialogue file
2. Number of unique user IDs
3. Missing users compared to demographics dataset
4. Duplicate users within each file
5. Line numbers for any duplicate entries

The script can verify either the original dialogue files or the merged files
after running the merge_missing_dialogues.py script.

Usage:
    # Verify original dialogue files
    python llm_behavior_adaptation/dialogue_dataset_creation/verify_dialogue_files.py

    # Verify merged dialogue files
    python llm_behavior_adaptation/dialogue_dataset_creation/verify_dialogue_files.py --use-merged

    # Verify only career advice dialogues
    python llm_behavior_adaptation/dialogue_dataset_creation/verify_dialogue_files.py --career-only

    # Verify only investment advice dialogues
    python llm_behavior_adaptation/dialogue_dataset_creation/verify_dialogue_files.py --investment-only

Exit codes:
    0 - All checks passed
    1 - Issues found (missing users, duplicates, or mismatched counts)
"""

import argparse
import csv
import json
import sys
from pathlib import Path


def load_demographics_user_ids(demographics_path):
    """Load user IDs from demographics CSV file."""
    user_ids = set()
    with open(demographics_path, 'r', encoding='utf-8') as f:
        reader = csv.DictReader(f)
        for row in reader:
            user_ids.add(row['D_INTERVIEW'])
    return user_ids


def analyze_dialogue_file(file_path):
    """
    Analyze a dialogue JSONL file.

    Returns:
        dict: Contains total_lines, unique_users, all_users (list), user_ids (set)
    """
    all_users = []
    user_ids = set()

    with open(file_path, 'r', encoding='utf-8') as f:
        for line in f:
            dialogue = json.loads(line)
            for user_id in dialogue.keys():
                all_users.append(user_id)
                user_ids.add(user_id)

    return {
        'total_lines': len(all_users),
        'unique_users': len(user_ids),
        'all_users': all_users,
        'user_ids': user_ids
    }


def find_duplicates(all_users):
    """Find duplicate user IDs in a list."""
    seen = set()
    duplicates = []

    for user_id in all_users:
        if user_id in seen:
            duplicates.append(user_id)
        else:
            seen.add(user_id)

    return list(set(duplicates))  # Return unique duplicate IDs


def print_verification_results(topic, file_path, analysis, demographics_ids):
    """Print formatted verification results for a dialogue file."""
    print(f"\n{topic} Dialogue File:")
    print(f"  File: {file_path}")
    print(f"  Total lines: {analysis['total_lines']}")
    print(f"  Unique users: {analysis['unique_users']}")

    # Check for missing users
    missing = demographics_ids - analysis['user_ids']
    if missing:
        print(f"  ❌ Missing users: {len(missing)}")
        print(f"     IDs: {sorted(list(missing))}")
    else:
        print(f"  ✓ No missing users")

    # Check for duplicates
    duplicates = find_duplicates(analysis['all_users'])
    if duplicates:
        print(f"  ❌ Duplicate users: {len(duplicates)}")
        print(f"     IDs: {sorted(duplicates)}")

        # Show line numbers for each duplicate
        for dup_id in sorted(duplicates):
            line_nums = [i for i, uid in enumerate(analysis['all_users']) if uid == dup_id]
            print(f"     - User {dup_id} appears at lines: {line_nums}")
    else:
        print(f"  ✓ No duplicates")

    # Overall status
    if not missing and not duplicates and analysis['unique_users'] == len(demographics_ids):
        print(f"  ✅ STATUS: PERFECT!")
    else:
        print(f"  ⚠️  STATUS: Issues found")


def main():
    parser = argparse.ArgumentParser(description="Verify dialogue files")
    parser.add_argument(
        "--career-only",
        action="store_true",
        help="Only verify career advice dialogues"
    )
    parser.add_argument(
        "--investment-only",
        action="store_true",
        help="Only verify investment advice dialogues"
    )
    parser.add_argument(
        "--use-merged",
        action="store_true",
        help="Verify merged files instead of original files"
    )
    args = parser.parse_args()

    # Paths
    demographics_path = "datasets/wvs_benchmarks/sampled_demographic_features.csv"

    if args.use_merged:
        career_path = "datasets/wvs_generated_dialogues/career_advice/all_samples_merged.jsonl"
        investment_path = "datasets/wvs_generated_dialogues/investment_advice/all_samples_merged.jsonl"
        file_type = "MERGED"
    else:
        career_path = "datasets/wvs_generated_dialogues/career_advice/all_samples.jsonl"
        investment_path = "datasets/wvs_generated_dialogues/investment_advice/all_samples.jsonl"
        file_type = "ORIGINAL"

    print("=" * 70)
    print(f"DIALOGUE FILES VERIFICATION ({file_type})")
    print("=" * 70)

    # Load demographics
    demographics_ids = load_demographics_user_ids(demographics_path)
    print(f"\nDemographics: {len(demographics_ids)} users")

    # Verify career advice (unless investment-only)
    if not args.investment_only:
        if Path(career_path).exists():
            career_analysis = analyze_dialogue_file(career_path)
            print_verification_results("Career", career_path, career_analysis, demographics_ids)
        else:
            print(f"\n❌ Career file not found: {career_path}")

    # Verify investment advice (unless career-only)
    if not args.career_only:
        if Path(investment_path).exists():
            investment_analysis = analyze_dialogue_file(investment_path)
            print_verification_results("Investment", investment_path, investment_analysis, demographics_ids)
        else:
            print(f"\n❌ Investment file not found: {investment_path}")

    # Summary
    print("\n" + "=" * 70)

    # Determine overall status
    all_good = True
    if not args.investment_only and Path(career_path).exists():
        career_analysis = analyze_dialogue_file(career_path)
        missing_career = demographics_ids - career_analysis['user_ids']
        duplicates_career = find_duplicates(career_analysis['all_users'])
        if missing_career or duplicates_career or career_analysis['unique_users'] != len(demographics_ids):
            all_good = False

    if not args.career_only and Path(investment_path).exists():
        investment_analysis = analyze_dialogue_file(investment_path)
        missing_investment = demographics_ids - investment_analysis['user_ids']
        duplicates_investment = find_duplicates(investment_analysis['all_users'])
        if missing_investment or duplicates_investment or investment_analysis['unique_users'] != len(demographics_ids):
            all_good = False

    if all_good:
        print("✅ VERIFICATION PASSED!")
        if args.use_merged:
            print("   Both merged files have 1000 unique users with no duplicates.")
            print("   Ready to replace original files.")
        else:
            print("   All dialogue files are complete and correct.")
    else:
        print("⚠️  VERIFICATION FAILED!")
        print("   Issues found in dialogue files. See details above.")
        sys.exit(1)

    print("=" * 70)


if __name__ == "__main__":
    main()
